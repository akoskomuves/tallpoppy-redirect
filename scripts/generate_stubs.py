#!/usr/bin/env python3
"""Generate static redirect stubs for tallpoppy.xyz -> tallpoppystudio.com.

GitHub Pages can't send a real 301 for a custom domain, and deep links that hit
404.html come back as HTTP 404 (bad for crawlers and App Review). This writes a
small `index.html` for every known studio path so those URLs return 200 with a
meta refresh + canonical to the same path on tallpoppystudio.com.

Path sources:
  1. https://tallpoppystudio.com/sitemap.xml
  2. the local studio repo (akoskomuves.github.io): every tracked */index.html
     and *.html page (skips trip/, 404.html, and `_`-prefixed template dirs)
  3. LEGACY_PATHS below: project Pages sites and old paths people linked to

Each path is checked against the live studio site and skipped unless it returns
200 (pass --no-check to skip that). Stubs this script wrote before and no longer
generates are removed; 404.html, CNAME and other hand-made files are never touched.

Re-run after the studio site adds pages:
    python3 scripts/generate_stubs.py [--studio-repo PATH] [--no-check]
"""
from __future__ import annotations

import argparse
import html
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import quote, urlparse

TARGET = "https://tallpoppystudio.com"
MARKER = "<!-- generated by scripts/generate_stubs.py -->"
ROOT = Path(__file__).resolve().parent.parent
DEFAULT_STUDIO_REPO = ROOT.parent / "akoskomuves.github.io"

EXCLUDE_PREFIXES = ("trip/",)
# Files copied verbatim instead of stubbed (Search Console verification must
# answer 200 with its own content on tallpoppy.xyz to keep that property verified).
VERBATIM = ("google24ee0e2d9f547ea5.html",)
# Paths that live outside the studio repo but exist on tallpoppystudio.com
# (GitHub project Pages sites) or were linked as tallpoppy.xyz URLs.
LEGACY_PATHS = [
    "aso-cross-localization/",
    "aso-cross-localization/REFERENCE.html",
    "aso-cross-localization/SKILL.html",
    "kumano-releases/",
]

TEMPLATE = """<!DOCTYPE html>
{marker}
<html lang="en">
<head>
    <meta charset="utf-8">
    <title>Moved to tallpoppystudio.com</title>
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="robots" content="noindex">
    <link rel="canonical" href="{url}">
    <meta http-equiv="refresh" content="0; url={url}">
    <script>
        location.replace("{target}" + location.pathname + location.search + location.hash);
    </script>
</head>
<body>
    <p>This page has moved to <a href="{url}">{url}</a>.</p>
</body>
</html>
"""


def sitemap_paths() -> list[str]:
    with urllib.request.urlopen(f"{TARGET}/sitemap.xml", timeout=20) as r:
        xml = r.read().decode("utf-8")
    out = []
    for loc in re.findall(r"<loc>\s*([^<\s]+)\s*</loc>", xml):
        u = urlparse(loc)
        if u.netloc.endswith("tallpoppystudio.com"):
            out.append(u.path.lstrip("/"))
    return out


def repo_paths(repo: Path) -> list[str]:
    files = subprocess.run(
        ["git", "-C", str(repo), "ls-files", "*.html"],
        check=True, capture_output=True, text=True,
    ).stdout.split()
    out = []
    for f in files:
        if f == "404.html" or f.startswith(EXCLUDE_PREFIXES) or f in VERBATIM:
            continue
        if any(part.startswith("_") for part in f.split("/")):
            continue
        out.append(f[: -len("index.html")] if f.endswith("index.html") else f)
    return out


def is_live(path: str) -> bool:
    req = urllib.request.Request(f"{TARGET}/{quote(path)}", method="HEAD")
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status == 200
    except urllib.error.HTTPError:
        return False  # real non-2xx answer from the studio site
    # Any other URLError (DNS, timeout, outage) propagates and aborts the run,
    # so a network blip can't make the cleanup below delete committed stubs.


def normalise(path: str) -> str | None:
    """Return a stub-able path ('' / 'dir/' / 'page.html'), or None to skip."""
    path = path.lstrip("/")
    if path == "" or path.endswith("/") or path.endswith(".html"):
        return path
    if "." in path.rsplit("/", 1)[-1]:
        return None  # non-HTML file (xml, png...): a meta refresh can't stand in
    return path + "/"


def stub_file(path: str) -> Path:
    return ROOT / (path if path.endswith(".html") else path + "index.html")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--studio-repo", type=Path, default=DEFAULT_STUDIO_REPO)
    ap.add_argument("--no-check", action="store_true", help="don't HEAD-check targets")
    args = ap.parse_args()

    paths = set(sitemap_paths()) | set(LEGACY_PATHS)
    if args.studio_repo.is_dir():
        paths |= set(repo_paths(args.studio_repo))
    else:
        print(f"warning: studio repo not found at {args.studio_repo}", file=sys.stderr)
    paths = {n for n in map(normalise, paths) if n is not None}
    paths = {p for p in paths if not p.startswith(EXCLUDE_PREFIXES) and ".." not in p}

    written: set[Path] = set()
    for path in sorted(paths):
        if not args.no_check and not is_live(path):
            print(f"skip (not 200 on studio): /{path}")
            continue
        url = html.escape(f"{TARGET}/{quote(path)}", quote=True)
        f = stub_file(path)
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(TEMPLATE.format(marker=MARKER, url=url, target=TARGET))
        written.add(f)
        print(f"stub /{path}")

    for name in VERBATIM:
        src = args.studio_repo / name
        if src.is_file():
            (ROOT / name).write_bytes(src.read_bytes())
            print(f"copy /{name}")

    for f in ROOT.rglob("*.html"):
        if ".git" in f.parts or f in written:
            continue
        if MARKER in f.read_text(errors="ignore"):
            f.unlink()
            print(f"removed stale stub {f.relative_to(ROOT)}")
    print(f"{len(written)} stubs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
